"""Router-lag probe: how does rollout-vs-train routing drift grow with parameter lag?

Diagnostic for the claim "a deeper async setting (larger sync interval N) gives a
larger train/inference router mismatch". In fully-async training a response is
generated by weights ``theta_gen`` and consumed by an update at weights
``theta_cur``; N only changes how many updates separate the two (generation-version
staleness plus the position inside the sync window). The FP8/BF16 precision gap is
the same for every N. So the quantity to measure is routing drift on a *fixed* set
of responses as a function of the update lag ``k``.

Protocol (driven by ``fully_async_router_lag_probe_main.py``):

  * Resume from a checkpoint at param version ``V0``. The first sync window only
    sees responses generated purely by ``V0`` (``min_global_steps == max_global_steps
    == V0``). A length-stratified subset of them becomes the probe set. For each
    probe response we keep its FP8 rollout routes ``R^mu_0`` and its BF16 train
    routes ``R^pi_0`` (free: the decoupled old_log_prob recompute in that window
    runs at ``V0``).
  * Training continues normally. Before the update at local step ``s`` (lag
    ``k = s - 1`` updates since ``V0``) the probe set is re-forwarded at the
    current weights, giving ``R^pi_k``.
  * Per lag we store ``D(mu_0, pi_k)`` (train/inference mismatch, the RDC score)
    and ``D(pi_0, pi_k)`` (pure lag, no precision gap), plus exact-set flip rate,
    top-K overlap mismatch, per-layer match rates and expert-usage counts for
    heatmaps. All scores come from ``compute_router_mismatch_metrics`` -- the same
    code the RDC filter uses.

This module holds the pure (Ray-free) pieces so they can be unit tested on CPU.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import torch
from omegaconf import OmegaConf

from verl.utils.router_mismatch_metrics import compute_router_mismatch_metrics

METRIC_PREFIX = "router_lag_probe"
_ALIGNMENT_CANDIDATES = (0, -1, 1)


@dataclass(frozen=True)
class ProbeSettings:
    probe_size: int
    max_lag: int
    length_bucket_edges: tuple[int, ...]
    output_dir: str
    seed: int
    metric_chunk: int
    batch_multiple: int
    num_experts: int
    smoothing_tau: float


def router_lag_probe_enabled(config) -> bool:
    return bool(OmegaConf.select(config, "router_lag_probe.enable", default=False))


def probe_settings(config) -> ProbeSettings:
    def sel(key, default):
        return OmegaConf.select(config, f"router_lag_probe.{key}", default=default)

    batch_multiple = max(int(sel("batch_multiple", 16)), 1)
    probe_size = (int(sel("probe_size", 256)) // batch_multiple) * batch_multiple
    if probe_size <= 0:
        raise ValueError(f"router_lag_probe.probe_size must be >= batch_multiple={batch_multiple}")
    output_dir = str(sel("output_dir", "") or "")
    if not output_dir:
        raise ValueError("router_lag_probe.output_dir must be set")
    edges = tuple(int(e) for e in (sel("length_bucket_edges", [2048, 4096, 8192, 12288]) or []))
    if list(edges) != sorted(edges):
        raise ValueError(f"router_lag_probe.length_bucket_edges must be ascending, got {edges}")
    num_experts = sel("num_experts", None)
    if num_experts is None:
        num_experts = OmegaConf.select(config, "router.expert_usage_num_experts", default=None)
    # Fix the expert count so per-chunk usage histograms always share one shape.
    num_experts = int(num_experts) if num_experts is not None else 128
    return ProbeSettings(
        probe_size=probe_size,
        max_lag=int(sel("max_lag", 128)),
        length_bucket_edges=edges,
        output_dir=output_dir,
        seed=int(sel("seed", 1234)),
        metric_chunk=max(int(sel("metric_chunk", 8)), 1),
        batch_multiple=batch_multiple,
        num_experts=num_experts,
        smoothing_tau=float(OmegaConf.select(config, "router.expert_usage_smoothing_tau", default=4096.0)),
    )


def length_buckets(lengths: torch.Tensor, edges: tuple[int, ...]) -> torch.Tensor:
    """Bucket id per response, same convention as RDC: bucket b is ``[edge_{b-1}, edge_b)``."""
    if not edges:
        return torch.zeros_like(lengths, dtype=torch.long)
    boundaries = torch.tensor(edges, dtype=lengths.dtype)
    return torch.bucketize(lengths, boundaries, right=True)


def bucket_quotas(probe_size: int, num_buckets: int) -> list[int]:
    base, extra = divmod(probe_size, num_buckets)
    return [base + (1 if b < extra else 0) for b in range(num_buckets)]


def select_probe_indices(
    eligible: torch.Tensor,
    bucket_ids: torch.Tensor,
    quota_left: list[int],
    budget_left: int,
    *,
    batch_multiple: int,
    backfill: bool,
    generator: torch.Generator,
) -> tuple[torch.Tensor, list[int]]:
    """Pick a length-stratified subset of eligible rows.

    Each bucket contributes up to its remaining quota. With ``backfill`` (last step
    of the capture window) unfilled quota is topped up from any bucket. The pick is
    trimmed to a multiple of ``batch_multiple`` so every probe chunk splits evenly
    across actor DP ranks.
    """
    num_buckets = len(quota_left)
    taken_per_bucket = [0] * num_buckets
    if budget_left <= 0:
        return torch.zeros(0, dtype=torch.long), taken_per_bucket

    chosen: list[list[int]] = [[] for _ in range(num_buckets)]
    leftovers: list[tuple[int, int]] = []
    for b in range(num_buckets):
        cand = torch.nonzero(eligible & (bucket_ids == b), as_tuple=False).flatten()
        if cand.numel() == 0:
            continue
        cand = cand[torch.randperm(cand.numel(), generator=generator)].tolist()
        take = min(max(quota_left[b], 0), len(cand))
        chosen[b] = cand[:take]
        leftovers.extend((idx, b) for idx in cand[take:])

    total = sum(len(c) for c in chosen)
    if backfill and total < budget_left and leftovers:
        order = torch.randperm(len(leftovers), generator=generator).tolist()
        for pos in order:
            if total >= budget_left:
                break
            idx, b = leftovers[pos]
            chosen[b].append(idx)
            total += 1

    # Never exceed the remaining budget, then round down to the DP multiple. Trim
    # from the fullest bucket so stratification is preserved as far as possible.
    excess = total - min(total, budget_left)
    excess += (total - excess) % batch_multiple
    while excess > 0:
        b = max(range(num_buckets), key=lambda i: len(chosen[i]))
        chosen[b].pop()
        excess -= 1

    taken_per_bucket = [len(c) for c in chosen]
    flat = sorted(idx for c in chosen for idx in c)
    return torch.tensor(flat, dtype=torch.long), taken_per_bucket


def crop_routes_to_response(routes: torch.Tensor, response_len: int) -> torch.Tensor:
    """Keep the last ``response_len`` positions and store as uint8.

    Rollout routes cover prompt+response ``[B, S, L, K]``; train routes from
    ``no_padding_2_padding`` already cover the response ``[B, R, L, K]``.
    ``compute_router_mismatch_metrics`` itself keeps the last ``R`` rollout
    positions and right-aligns train routes, so cropping both to ``R`` changes no
    score while halving storage.
    """
    if routes.is_nested:
        routes = routes.to_padded_tensor(0)
    routes = routes[:, -response_len:]
    if routes.dtype.is_floating_point:
        routes = routes.to(dtype=torch.int64)
    if routes.numel() > 0 and int(routes.max().item()) > 255:
        raise ValueError("expert ids exceed uint8 range; cannot cache routes compactly")
    return routes.to(dtype=torch.uint8).contiguous()


def pick_alignment(
    reference_routes: torch.Tensor,
    current_routes: torch.Tensor,
    response_mask: torch.Tensor,
    *,
    num_experts: int,
    smoothing_tau: float,
    max_rows: int = 16,
) -> int:
    """Choose the position shift once (same rule as RDC: best top-K set match), then freeze it."""
    rows = min(max_rows, int(reference_routes.shape[0]))
    result = compute_router_mismatch_metrics(
        reference_routes[:rows],
        current_routes[:rows],
        response_mask[:rows],
        metric_prefix=METRIC_PREFIX,
        alignments=_ALIGNMENT_CANDIDATES,
        metric_mode="exact_set",
        expert_usage_smoothing_tau=smoothing_tau,
        expert_usage_num_experts=num_experts,
    )
    return int(result.alignment)


def compare_routes(
    reference_routes: torch.Tensor,
    current_routes: torch.Tensor,
    response_mask: torch.Tensor,
    *,
    alignment: int,
    num_experts: int,
    smoothing_tau: float,
    chunk: int = 8,
) -> dict[str, torch.Tensor]:
    """Per-response routing drift between a reference route set and the current one.

    Returns per-response ``d_route`` (smoothed expert-usage L1, the RDC score),
    ``d_route_raw``, ``flip_rate`` (fraction of layers whose top-K set changed,
    averaged over tokens), ``overlap_mismatch`` (1 - |R_ref ∩ R_cur| / K), plus
    per-layer token match sums and per-response expert-usage counts ``[B, L, E]``.
    """
    batch_size = int(reference_routes.shape[0])
    parts: dict[str, list[torch.Tensor]] = {
        "d_route": [],
        "d_route_raw": [],
        "flip_rate": [],
        "overlap_mismatch": [],
        "valid_tokens": [],
        "ref_counts": [],
        "cur_counts": [],
    }
    layer_match_sum = None
    token_count = 0.0

    def call(mode, sl, capture=False):
        return compute_router_mismatch_metrics(
            reference_routes[sl],
            current_routes[sl],
            response_mask[sl],
            metric_prefix=METRIC_PREFIX,
            alignments=(alignment,),
            metric_mode=mode,
            expert_usage_smoothing_tau=smoothing_tau,
            expert_usage_num_experts=num_experts,
            capture_expert_usage_counts=capture,
        )

    for start in range(0, batch_size, chunk):
        sl = slice(start, min(start + chunk, batch_size))
        usage = call("expert_usage_l1", sl, capture=True)
        overlap = call("overlap_fraction", sl)
        exact = call("exact_set", sl)

        parts["d_route"].append(usage.seq_mismatch.float().cpu())
        parts["d_route_raw"].append(usage.expert_usage_distances["tv_raw"].float().cpu())
        parts["valid_tokens"].append(usage.seq_valid_token_count.float().cpu())
        parts["overlap_mismatch"].append(overlap.seq_mismatch.float().cpu())
        parts["flip_rate"].append(exact.seq_mismatch.float().cpu())
        parts["ref_counts"].append(usage.expert_usage_counts["rollout"].cpu())
        parts["cur_counts"].append(usage.expert_usage_counts["train"].cpu())

        chunk_tokens = float(usage.metrics.get(f"{METRIC_PREFIX}/response_token_count", 0.0))
        if chunk_tokens > 0:
            layer_count = int(reference_routes.shape[2])
            rates = torch.tensor(
                [usage.metrics[f"{METRIC_PREFIX}/layer_{i}/response_token_match_rate"] for i in range(layer_count)],
                dtype=torch.float64,
            )
            layer_match_sum = rates * chunk_tokens if layer_match_sum is None else layer_match_sum + rates * chunk_tokens
            token_count += chunk_tokens

    out = {key: torch.cat(vals) for key, vals in parts.items()}
    out["layer_match_sum"] = layer_match_sum if layer_match_sum is not None else torch.zeros(0, dtype=torch.float64)
    out["token_count"] = torch.tensor(token_count, dtype=torch.float64)
    return out


def merge_comparisons(items: list[dict[str, torch.Tensor]]) -> dict[str, torch.Tensor]:
    merged = {}
    for key in items[0]:
        if key == "layer_match_sum":
            merged[key] = sum(item[key] for item in items)
        elif key == "token_count":
            merged[key] = sum(item[key] for item in items)
        else:
            merged[key] = torch.cat([item[key] for item in items])
    return merged


def masked_mean_abs_diff(a: torch.Tensor, b: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
    """Per-response mean |a - b| over valid tokens (probability channel next to the routing one)."""
    m = mask.to(dtype=torch.float32)
    diff = (a.float() - b.float()).abs() * m
    return diff.sum(dim=-1) / m.sum(dim=-1).clamp(min=1.0)


def update_lag(step_index: int, gen_version: np.ndarray, v0: int, sync_interval: int) -> np.ndarray:
    """Updates between a response's generation weights and the weights at local step ``step_index``.

    Weights for version ``v`` are published after ``(v - V0) * N`` updates since
    resume; the update at local step ``s`` (1-based) runs on weights that have seen
    ``s - 1`` updates. For partial rollouts pass ``min_global_steps`` to get the lag
    of the oldest tokens and ``max_global_steps`` for the newest.
    """
    return (step_index - 1) - (gen_version.astype(np.int64) - int(v0)) * int(sync_interval)


def summarize(comparison: dict[str, torch.Tensor]) -> dict[str, float]:
    tokens = float(comparison["token_count"])
    layer_sum = comparison["layer_match_sum"]
    token_flip = 1.0 - float(layer_sum.sum()) / (tokens * layer_sum.numel()) if tokens > 0 and layer_sum.numel() else 0.0
    return {
        "d_route_mean": float(comparison["d_route"].mean()),
        "d_route_raw_mean": float(comparison["d_route_raw"].mean()),
        "flip_rate_mean": float(comparison["flip_rate"].mean()),
        "overlap_mismatch_mean": float(comparison["overlap_mismatch"].mean()),
        "token_layer_flip_rate": token_flip,
    }
